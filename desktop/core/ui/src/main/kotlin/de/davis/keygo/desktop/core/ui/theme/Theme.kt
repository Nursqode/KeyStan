/**
 * The app's theme.
 *
 * Material 3's default typography is used as-is, matching the Android app, which also takes the
 * defaults; only the palette and the secret text style are app-specific.
 *
 * Unlike the phone there is no dynamic colour: the desktop has no wallpaper-derived palette, and
 * inventing one would make the two platforms look different, which is the opposite of the goal.
 */
@Composable
fun KeyGoTheme(darkTheme: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {
    MaterialTheme(
        colorScheme = if (darkTheme) darkScheme else lightScheme,
        typography = Typography(),
        content = content,
    )
}

private val Secret = TextStyle(
    fontFamily = FontFamily.Monospace,
    fontFeatureSettings = "tnum",
)

/**
 * The ambient text style with secret typography applied: monospace so lookalike characters stay
 * apart, tabular figures so digits keep their column while a value scrolls.
 *
 * Use it for anything the user reads character by character - passwords, card numbers, CVVs, TOTP
 * codes and recovery codes.
 */
val secretTextStyle: TextStyle
    @Composable
    @ReadOnlyComposable
    get() = LocalTextStyle.current.merge(Secret)
